// Regenerate the mock's pure settings policy from the production catalogue.
package main

import (
	"go/format"
	"os"
	"path/filepath"
	"strings"
)

func main() {
	root := os.Args[1]
	for _, name := range []string{"settings", "catalog"} {
		b, err := os.ReadFile(filepath.Join(root, "internal/notification/domain", name+".go"))
		must(err)
		s := strings.Replace(string(b), "package domain", "package store", 1)
		s = strings.ReplaceAll(s, "\"github.com/leha-creator/chanly/internal/platform/apperr\"", "")
		s = strings.ReplaceAll(s, "apperr.Conflict(", "settingsConflict(")
		s = strings.ReplaceAll(s, "apperr.Validation(", "settingsValidation(")
		s = strings.ReplaceAll(s, "apperr.Forbidden(", "Forbidden(")
		s = "// Code generated by scripts/mock-settings. DO NOT EDIT.\n" + s
		out, err := format.Source([]byte(s))
		must(err)
		must(os.WriteFile(filepath.Join(root, "mockapi/internal/store", name+"_policy.gen.go"), out, 0644))
	}
}
func must(err error) {
	if err != nil {
		panic(err)
	}
}
